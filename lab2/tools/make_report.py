FONT = 'Times New Roman'


def fmt_run(r, bold=False, italic=False, size=14):
    r.font.name = FONT
    r._r.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), FONT)
    r.font.size = Pt(size)
    r.bold = bold
    r.italic = italic


def rich(p, text, size=14, bold_all=False):
    """**жирный** фрагменты внутри текста."""
    for i, part in enumerate(re.split(r'\*\*', text)):
        if part:
            fmt_run(p.add_run(part), bold=bold_all or i % 2 == 1, size=size)


def P(text='', align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True, bold=False, after=0, before=0, page_break=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = align
    pf.first_line_indent = Cm(1.25) if indent else None
    pf.space_after = Pt(after)
    pf.space_before = Pt(before)
    pf.line_spacing = 1.15
    if page_break:
        pf.page_break_before = True
    rich(p, text, bold_all=bold)
    return p


def H(text, page_break=False):
    p = P(text, align=WD_ALIGN_PARAGRAPH.CENTER, indent=False, bold=True, before=12, after=6, page_break=page_break)
    p.paragraph_format.keep_with_next = True
    return p


def SH(text):
    p = P(text, align=WD_ALIGN_PARAGRAPH.LEFT, indent=False, bold=True, before=8, after=2)
    p.paragraph_format.keep_with_next = True
    return p


def BUL(text):
    p = P('•\t' + text, indent=False)
    pf = p.paragraph_format
    pf.left_indent = Cm(1.25)
    pf.first_line_indent = Cm(-0.6)
    pf.tab_stops.add_tab_stop(Cm(1.25))
    return p


def STEPS(items):
    for i, t in enumerate(items, 1):
        p = P(f'{i}. {t}', indent=False)
        p.paragraph_format.left_indent = Cm(0.6)


fig_no = [0]


def FIG(path, caption, width_in=6.0, max_h_in=7.6, crop=None):
    if crop:
        im = Image.open(path)
        out = os.path.join(TMP, os.path.basename(path))
        im.crop(crop).save(out)
        path = out
    w, h = Image.open(path).size
    width = min(width_in, max_h_in * w / h)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = True
    p.paragraph_format.space_before = Pt(6)
    p.add_run().add_picture(path, width=Inches(width))
    fig_no[0] += 1
    c = P(f'Рисунок {fig_no[0]}: {caption}', align=WD_ALIGN_PARAGRAPH.CENTER, indent=False, after=8)
    return fig_no[0]


tab_no = [0]


def TABLE(header, rows, caption, widths=None, size=12):
    tab_no[0] += 1
    cp = P(f'Таблица {tab_no[0]} – {caption}', align=WD_ALIGN_PARAGRAPH.LEFT, indent=False, before=6, after=2)
    cp.paragraph_format.keep_with_next = True
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, htext in enumerate(header):
        cell = t.rows[0].cells[j]
        cell.text = ''
        rich(cell.paragraphs[0], str(htext), size=size, bold_all=True)
    for i, row in enumerate(rows, 1):
        for j, v in enumerate(row):
            cell = t.rows[i].cells[j]
            cell.text = ''
            rich(cell.paragraphs[0], str(v), size=size)
    if widths:
        for row in t.rows:
            for j, wd in enumerate(widths):
                row.cells[j].width = Cm(wd)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


